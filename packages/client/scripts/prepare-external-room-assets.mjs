import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const client = path.join(root, "packages/client");
const shared = path.join(root, "packages/shared/src");
const packs = [
  { source: "assets/incoming/interior-sets/pixel-modern-office", id: "pixel-modern-office", label: "Pixel Modern Office" },
  { source: "assets/incoming/interior-sets/cozy-home-interiors", id: "cozy-home-interiors", label: "Cozy Home Interiors" },
  { source: "assets/incoming/park-sets/city-park-and-playground", id: "city-park-and-playground", label: "City Park and Playground" },
];

const definitions = [];
const walls = [];
for (const pack of packs) {
  const sourceDir = path.join(client, pack.source);
  const indexPath = path.join(sourceDir, "asset-index.json");
  const manifest = JSON.parse(await readFile(indexPath, "utf8"));
  const license = pack.id === "city-park-and-playground" ? "LICENSE-CC0-1.0.txt" : null;
  const runtimeDir = path.join(client, "public/assets/external", pack.id);
  await mkdir(runtimeDir, { recursive: true });
  if (license) await cp(path.join(sourceDir, license), path.join(runtimeDir, license));

  for (const model of manifest) {
    const file = model.file;
    if (!file?.toLowerCase().endsWith(".glb") || model.category === "scene" || model.category === "starter-scene") continue;
    const dimensions = Array.isArray(model.dimensionsMeters)
      ? model.dimensionsMeters
      : String(model.sizeMeters ?? model.collisionAabbMeters ?? "").split("x").map((part) => Number(part.trim()));
    if (dimensions.length !== 3 || dimensions.some((dimension) => !Number.isFinite(dimension) || dimension <= 0)) continue;
    const [width, height, depth] = dimensions;
    const relativeFile = file.replaceAll("\\", "/");
    await mkdir(path.dirname(path.join(runtimeDir, relativeFile)), { recursive: true });
    await cp(path.join(sourceDir, relativeFile), path.join(runtimeDir, relativeFile));

    const rawCategory = model.category;
    const category = rawCategory === "walls" || rawCategory === "boundary" ? "wall" : rawCategory === "tiles" ? "tile" : "prop";
    const asset = `external-${pack.id}-${model.slug ?? model.id ?? path.basename(file, ".glb")}`;
    if (category === "wall") walls.push(asset);
    const collision = category === "prop" && Math.max(width, depth) >= 0.3 && !/book|paper|food|coffee|mug|mouse|keyboard|monitor|screen|lamp|flower|decoration|small item/i.test(model.title ?? "");
    definitions.push({
      asset,
      label: model.title ?? path.basename(file, ".glb"),
      height,
      width,
      depth,
      collision,
      ...(collision ? { collisionWidth: width, collisionDepth: depth } : {}),
      modelUrl: `/assets/external/${pack.id}/${relativeFile}`,
      format: "gltf",
      group: category === "tile" ? "Floor tiles" : category === "wall" ? `Wall · ${pack.label}` : `Imported · ${pack.label}`,
      ...(category === "wall" ? { wallAxis: "x" } : {}),
    });
  }
}

const source = `// Generated by packages/client/scripts/prepare-external-room-assets.mjs from CC0 asset indexes.\nimport type { RoomPropDefinition } from "./roomLayout.js";\n\nexport const EXTERNAL_WALL_ASSET_IDS = ${JSON.stringify(walls, null, 2)} as const;\n\nexport const EXTERNAL_ROOM_PROP_CATALOG: ReadonlyArray<RoomPropDefinition> = ${JSON.stringify(definitions, null, 2)};\n`;
await writeFile(path.join(shared, "externalRoomProps.ts"), source);
console.log(`Prepared ${definitions.length} CC0 models (${walls.length} wall modules), copied to client runtime assets.`);
